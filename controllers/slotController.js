const Slot = require('../models/Slot');
const Stylist = require('../models/Stylist');
const Holiday = require('../models/Holiday');
const { sendSuccess, sendError } = require('../utils/responseHandler');
const asyncWrapper = require('../utils/asyncWrapper');

// Helper to format minutes to HH:mm string
const formatTime = (minutes) => {
  const h = Math.floor(minutes / 60);
  const m = minutes % 60;
  return `${h.toString().padStart(2, '0')}:${m.toString().padStart(2, '0')}`;
};

/**
 * @desc    Fetch Available Time Slots for Booking
 * @route   GET /api/slots/available
 * @access  Public
 */
exports.getAvailableSlots = asyncWrapper(async (req, res) => {
  const { date, stylistId, duration } = req.query;

  if (!date) {
    return sendError(res, 'Date parameter (YYYY-MM-DD) is required', 400);
  }

  // 1. Check if date is a salon holiday
  const holiday = await Holiday.findOne({ date });
  if (holiday) {
    return sendSuccess(
      res,
      `Salon is closed on ${date} (${holiday.reason})`,
      [],
      200,
      { isHoliday: true, reason: holiday.reason }
    );
  }

  // 2. Query filter
  const filter = { date, status: 'available' };
  if (stylistId && stylistId.match(/^[0-9a-fA-F]{24}$/)) {
    filter.stylist = stylistId;
  }

  let slots = await Slot.find(filter)
    .populate('stylist', 'name title avatar')
    .sort({ startTime: 1 });

  // 3. Auto-generate default slots for the day if none exist yet for requested stylist
  if (slots.length === 0 && stylistId) {
    const stylist = await Stylist.findById(stylistId);
    if (stylist && stylist.isActive) {
      const generated = await autoGenerateDaySlots(stylistId, date, Number(duration) || 60);
      slots = generated;
    }
  }

  return sendSuccess(res, 'Available slots fetched successfully', slots);
});

/**
 * Helper: Auto-generate default day time slots (10:00 AM to 11:00 PM)
 */
async function autoGenerateDaySlots(stylistId, date, slotDuration = 60) {
  const startMinutes = 10 * 60; // 10:00 AM
  const endMinutes = 23 * 60;   // 11:00 PM
  const newSlots = [];

  for (let current = startMinutes; current + slotDuration <= endMinutes; current += slotDuration) {
    const startTime = formatTime(current);
    const endTime = formatTime(current + slotDuration);

    newSlots.push({
      stylist: stylistId,
      date,
      startTime,
      endTime,
      status: 'available',
    });
  }

  try {
    await Slot.insertMany(newSlots, { ordered: false });
  } catch (err) {
    // Ignore duplicate key errors if some slots already existed
  }

  return await Slot.find({ stylist: stylistId, date, status: 'available' })
    .populate('stylist', 'name title avatar')
    .sort({ startTime: 1 });
}

/**
 * @desc    Generate Time Slots for Stylist & Date (Admin)
 * @route   POST /api/slots/generate
 * @access  Private (Super Admin, Manager)
 */
exports.generateSlots = asyncWrapper(async (req, res) => {
  const { stylistId, date, slotDurationMinutes, startHour, endHour } = req.body;

  const stylist = await Stylist.findById(stylistId);
  if (!stylist) {
    return sendError(res, 'Stylist not found', 404);
  }

  const duration = slotDurationMinutes || 60;
  const startMins = (startHour !== undefined ? startHour : 10) * 60;
  const endMins = (endHour !== undefined ? endHour : 23) * 60;

  const newSlots = [];
  for (let current = startMins; current + duration <= endMins; current += duration) {
    const startTime = formatTime(current);
    const endTime = formatTime(current + duration);

    newSlots.push({
      stylist: stylistId,
      date,
      startTime,
      endTime,
      status: 'available',
    });
  }

  let createdSlots = [];
  try {
    createdSlots = await Slot.insertMany(newSlots, { ordered: false });
  } catch (err) {
    // Return existing + newly inserted slots
  }

  const allSlots = await Slot.find({ stylist: stylistId, date }).sort({ startTime: 1 });
  return sendSuccess(res, `Time slots generated for ${stylist.name} on ${date}`, allSlots, 201);
});

/**
 * @desc    Block or Unblock a Time Slot (Admin)
 * @route   PATCH /api/slots/:id/block
 * @access  Private (Super Admin, Manager)
 */
exports.toggleBlockSlot = asyncWrapper(async (req, res) => {
  const { status } = req.body;

  if (!['available', 'blocked'].includes(status)) {
    return sendError(res, "Status must be 'available' or 'blocked'", 400);
  }

  let slot = await Slot.findById(req.params.id);
  if (!slot) {
    return sendError(res, 'Slot not found', 404);
  }

  if (slot.status === 'booked') {
    return sendError(res, 'Cannot change status of a currently booked slot', 400);
  }

  slot.status = status;
  await slot.save();

  return sendSuccess(res, `Slot status updated to ${status}`, slot);
});
